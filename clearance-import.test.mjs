import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const source = fs.readFileSync(new URL('./clearance-import.js', import.meta.url), 'utf8');
const M = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
vm.runInThisContext(fs.readFileSync(new URL('./vendor/xlsx.full.min.js', import.meta.url), 'utf8'));
let checks = 0;
const eq = (actual, expected) => { assert.equal(actual, expected); checks++; };
const deep = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const throws = (fn, regex) => { assert.throws(fn, regex); checks++; };
const rejects = async (fn, regex) => { await assert.rejects(fn, regex); checks++; };
const valid = () => ['蓝牙音箱', '001-SPK', 120, 0.8, 42, 30, 25, 12, 'https://www.amazon.com/dp/B0EXAMPLE01', 'https://example.com/products/speaker.jpg', 29.99, '', '00012345', '2026-10-08', '保持原包装'];
const grid = (...rows) => [M.HEADERS, ...rows];
const changed = (index, value) => { const row = valid(); row[index] = value; return M.validateRows(grid(row)); };
const file = (name, bytes) => ({ name, size: bytes.byteLength, arrayBuffer: async () => bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) });

let result = M.validateRows(grid(valid()));
eq(result.total, 1); eq(result.validCount, 1); eq(result.errorCount, 0);
eq(result.rows[0].line, 2); eq(result.rows[0].product.currency, 'USD');
deep(result.rows[0].product.dimensions, [42, 30, 25]);
eq(result.rows[0].product.received, 0); eq(result.rows[0].product.delivered, 0);
eq(result.rows[0].product.sku, '001-SPK'); eq(result.rows[0].product.tracking, '00012345');
result = M.validateRows(grid([], ['', ' '], valid()));
eq(result.total, 1); eq(result.rows[0].line, 4);
for (const index of [0, 2, 8, 9]) eq(changed(index, '').errorCount, 1);
for (const value of [0, -1, 0.5, '120件', Infinity, 9007199254740992]) eq(changed(2, value).errorCount, 1);
for (const value of [-1, 0.5, '12箱']) eq(changed(7, value).errorCount, 1);
for (const index of [3, 4, 5, 6, 10]) eq(changed(index, -0.1).errorCount, 1);
for (const index of [3, 4, 5, 6, 7, 10]) eq(changed(index, '').errorCount, 0);
for (const value of ['javascript:alert(1)', 'data:image/png;base64,xxx', 'https://', 'ftp://example.com/image.png']) eq(changed(9, value).errorCount, 1);
eq(changed(8, 'http://example.com/product').errorCount, 0);
eq(changed(11, 'cad').rows[0].product.currency, 'CAD');
eq(changed(11, '美元').errorCount, 1);
eq(changed(13, '2026-02-30').errorCount, 1);
eq(changed(13, '2026/10/08').errorCount, 1);
eq(changed(13, '').errorCount, 0);
for (const value of ['=SUM(1,2)', '+SUM(1,2)', '@SUM(1,2)', { v: 120, f: 'SUM(1,2)' }]) eq(changed(2, value).errorCount, 1);
result = M.validateRows(grid(valid(), valid()));
eq(result.errorCount, 2); eq(result.rows[0].errors.some(text => text.includes('第 3')), true);
const second = valid(); second[1] = '001-spk';
eq(M.validateRows(grid(valid(), second)).errorCount, 2);
eq(changed(1, '').errorCount, 0);
throws(() => M.validateRows([]), /文件为空/);
throws(() => M.validateRows([['产品名称', ...M.HEADERS.slice(1)], valid()]), /表头/);
throws(() => M.validateRows([M.HEADERS]), /未找到产品/);
throws(() => M.validateRows(grid(...Array.from({ length: 501 }, (_, i) => { const row = valid(); row[1] = `SKU-${i}`; return row; }))), /500/);
eq(M.validateRows(grid(...Array.from({ length: 500 }, (_, i) => { const row = valid(); row[1] = `SKU-${i}`; return row; }))).validCount, 500);
eq(changed(15, '多余数据').errorCount, 1);

const csvEncode = value => '"' + String(value).replaceAll('"', '""') + '"';
const csvProduct = valid(); csvProduct[0] = '音箱,蓝色'; csvProduct[14] = '备注含 "引号"\n换行';
const csv = grid(csvProduct).map(row => row.map(csvEncode).join(',')).join('\r\n');
result = await M.readImportFile(file('products.csv', Buffer.from('\uFEFF' + csv, 'utf8')));
eq(result.validCount, 1); eq(result.rows[0].product.name, '音箱,蓝色');
eq(result.rows[0].product.requirement, '备注含 "引号"\n换行');
throws(() => M.parseCsv('a,"未闭合'), /未闭合/);
throws(() => M.parseCsv('a,"b"oops'), /多余内容/);
await rejects(() => M.readImportFile(file('products.xls', Buffer.from('no'))), /xlsx 或 .csv/);
await rejects(() => M.readImportFile({ name: 'large.xlsx', size: 11 * 1024 * 1024, arrayBuffer: async () => new ArrayBuffer(0) }), /10 MB/);

const templateBytes = fs.readFileSync(new URL('./清货导入模板.xlsx', import.meta.url));
const template = XLSX.read(templateBytes, { type: 'buffer', cellFormula: true });
deep(template.SheetNames, ['清货产品', '填写说明']);
deep(XLSX.utils.sheet_to_json(template.Sheets['清货产品'], { header: 1, blankrows: false })[0], [...M.HEADERS]);
await rejects(() => M.readImportFile(file('blank.xlsx', templateBytes)), /未找到产品/);

const wb = XLSX.utils.book_new();
const excelRow = valid(); excelRow[13] = new Date('2026-10-08T00:00:00Z');
const ws = XLSX.utils.aoa_to_sheet(grid(excelRow));
XLSX.utils.book_append_sheet(wb, ws, '清货产品');
let bytes = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
result = await M.readImportFile(file('good.xlsx', bytes));
eq(result.validCount, 1); eq(result.rows[0].product.shipped, '2026-10-08');
ws.C2 = { t: 'n', v: 120, f: 'SUM(100,20)' };
bytes = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
result = await M.readImportFile(file('formula.xlsx', bytes));
eq(result.errorCount, 1); eq(result.rows[0].errors.some(text => text.includes('禁止填写公式')), true);
console.log(`清货导入测试通过 ${checks} 项断言。`);
